import type { Localized, Product, ProductTag } from "@/types";
import { ingredients, type IngredientKey } from "./ingredients";

interface DishInput {
  slug: string;
  category: Product["category"];
  name: Localized;
  description: Localized;
  ingredients: IngredientKey[];
  weight: number;
  unit?: Product["unit"];
  pieces?: number;
  price: number;
  popularity: number;
  tags?: ProductTag[];
  available?: boolean;
  /** File name inside /public/images/products without extension. */
  image: string;
  imageAlt: Localized;
}

function dish(input: DishInput): Product {
  return {
    id: input.slug,
    slug: input.slug,
    category: input.category,
    name: input.name,
    description: input.description,
    ingredients: input.ingredients.map((key) => ingredients[key]),
    weight: input.weight,
    unit: input.unit ?? "g",
    pieces: input.pieces,
    price: input.price,
    popularity: input.popularity,
    tags: input.tags ?? [],
    available: input.available ?? true,
    image: `/images/products/${input.image}.webp`,
    imageAlt: input.imageAlt,
  };
}

